-- ให้ admin เดิมทุกคนมีสิทธิ์ครบทุกส่วน กันเมนูหายหลังเปลี่ยนโมเดล
-- (hasPermission เช็คจาก permissions[] ตรงๆ ไม่ผูก role แล้ว — role='admin' = สิทธิ์จัดการบัญชี/ผู้ตรวจเท่านั้น)
